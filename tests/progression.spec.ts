  await page.clock.fastForward(job.endsAt - (epoch + 1000) + 3000)
  await page.clock.runFor(1200)
  if (await page.getByRole('button', { name: '소중히 간직할게 ♡' }).count()) await page.getByRole('button', { name: '소중히 간직할게 ♡' }).click()
