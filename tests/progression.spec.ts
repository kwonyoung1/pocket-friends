test('backup restore preserves pictures and progress, rejects corruption, and recovers from IndexedDB alone', async ({ page }) => {
  await seed(page, fixture())
  const backup = fixture(); world(backup).coins = 777; growth(backup.friends[0]).level = 5; growth(backup.friends[0]).xp = 12
  backup.friends[0].photo = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = c.height = 32; c.getContext('2d')!.fillRect(0, 0, 32, 32); return c.toDataURL('image/png') })
  await page.getByLabel('게임 백업 선택').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  await page.getByRole('button', { name: '현재 게임 백업 후 복원' }).click()
  await expect(page.getByRole('button', { name: '보유 코인 777' })).toBeVisible()
  await expect(page.getByTestId('room-momo').getByRole('img', { name: '모모의 등록 사진' })).toBeVisible()
  await page.getByLabel('게임 백업 선택').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{bad') })
  await expect(page.getByRole('status')).toContainText('복원하지 못했어요')
  expect((await snapshot(page)).world.coins).toBe(777)
  await page.waitForFunction(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const r = indexedDB.open('pocket-friends-stage-two'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) })
    const raw = await new Promise<string>((resolve, reject) => { const r = db.transaction('saves').objectStore('saves').get('current'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) }); db.close()
    return raw && JSON.parse(raw).world.coins === 777
  })
  await page.evaluate(() => { localStorage.removeItem('pocket-friends-v1'); Storage.prototype.setItem = () => { throw Error('local storage unavailable') } })
  await page.reload()
  await expect(page.getByRole('button', { name: '보유 코인 777' })).toBeVisible()
  await expect(page.getByTestId('room-momo').getByRole('img', { name: '모모의 등록 사진' })).toBeVisible()
})
