import { test, expect } from '@playwright/test'
import type { Page, Locator } from '@playwright/test'
import { walkable } from '../src/navigation'
import { createFriends } from '../src/game'
const epoch = new Date('2026-10-15T03:00:00Z')
test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: epoch })
  await page.clock.pauseAt(new Date(epoch.getTime() + 1000))
  await page.goto('/')
})
async function point(actor: Locator, y = .45) {
  await actor.scrollIntoViewIfNeeded()
  const rect = await actor.locator('.friend-figure').boundingBox()
  if (!rect) throw Error('Character image missing')
  return { x: rect.x + rect.width / 2, y: rect.y + rect.height * y }
}
async function hold(page: Page, actor: Locator, y = .45) {
  const p = await point(actor, y)
  await page.mouse.move(p.x, p.y); await page.mouse.down(); await page.clock.runFor(30)
  return p
}
async function release(page: Page) { await page.mouse.up(); await page.clock.runFor(100) }
async function saved(page: Page, id = 'momo') {
  return page.evaluate(id => JSON.parse(localStorage.getItem('pocket-friends-v1')!).friends.find((f: {id: string}) => f.id === id), id)
}
test('short head/body taps react once, share the panel cooldown, and keyboard selection remains available', async ({ page }) => {
  const actor = page.getByTestId('room-momo')
  await hold(page, actor); await release(page)
  await expect(actor).toHaveAttribute('data-phase', 'delighted')
  await expect(actor).toHaveAttribute('data-zone', 'head')
  await expect(actor.locator('.pet-heart')).toHaveCount(2)
  await expect(actor.locator('[data-expression=smile]')).toHaveCount(1)
  expect((await saved(page)).stats.affection).toBe(21)
  await page.getByRole('button', { name: /쓰다듬기 행복/ }).click()
  expect((await saved(page)).stats.affection).toBe(21)
  const previousLine = await actor.locator('.speech').textContent()
  await hold(page, actor, .85); await release(page)
  await expect(actor).toHaveAttribute('data-zone', 'body')
  await expect(actor.locator('.pet-heart')).toHaveCount(1)
  await expect(actor.locator('.speech')).not.toHaveText(previousLine!)
  expect((await saved(page)).stats.affection).toBe(21)
  await page.getByRole('button', { name: '비비 상태 확인' }).click()
  await expect(page.getByRole('complementary', { name: '비비 돌보기' })).toBeVisible()
  const bibi = page.getByTestId('room-bibi'); await bibi.focus(); await page.keyboard.press('Enter'); await page.clock.runFor(100)
  expect((await saved(page, 'bibi')).stats.affection).toBe(21)
})
test('a held pet progresses at .8 and 2 seconds, closes eyes, emits hearts and pays only once', async ({ page }) => {
  const actor = page.getByTestId('room-momo')
  const p = await hold(page, actor)
  await page.mouse.move(p.x + 3, p.y + 2)
  await page.clock.runFor(790)
  await expect(actor).toHaveAttribute('data-phase', 'petting')
  await expect(actor.locator('[data-expression=closed]')).toHaveCount(1)
  await page.clock.runFor(1250)
  await expect(actor).toHaveAttribute('data-phase', 'bonding')
  await expect(actor.locator('.pet-heart')).toHaveCount(7)
  await expect(actor.locator('.speech')).toContainText(/냐아/)
  expect((await saved(page)).stats.affection).toBe(23)
  const bubble = await actor.locator('.speech').textContent()
  await page.clock.runFor(3100)
  expect((await saved(page)).stats.affection).toBe(23)
  await expect(actor.locator('.speech')).toHaveText(bubble!)
  await release(page)
  await expect(actor).toHaveAttribute('data-phase', 'settling')
  await page.clock.runFor(1700)
  await expect(actor).toHaveAttribute('data-phase', 'idle')
  await page.clock.runFor(800)
  expect(await actor.getAttribute('data-moving') === 'true' || await actor.getAttribute('data-x') !== '330.0' || await actor.getAttribute('data-y') !== '350.0').toBe(true)
})
test('drag from a pending long pet cancels pet rewards, avoids furniture and persists a valid drop', async ({ page }) => {
  const actor = page.getByTestId('room-momo')
  const p = await hold(page, actor)
  await page.clock.runFor(1000)
  const room = await page.locator('.room').boundingBox()
  if (!room) throw Error('Room missing')
  await page.mouse.move(p.x + 400 / 1000 * room.width, p.y + 120 / 640 * room.height, { steps: 5 })
  await page.clock.runFor(300)
  await expect(actor).toHaveAttribute('data-phase', 'dragging')
  await expect(actor.locator('.pet-heart')).toHaveCount(0)
  await expect(actor.locator('.friend-lift')).toHaveCSS('transform', /matrix/)
  await page.clock.runFor(2100)
  await release(page)
  await expect(actor).toHaveAttribute('data-phase', 'landing')
  const data = await saved(page)
  expect(data.stats.affection).toBe(20); expect(walkable(data)).toBe(true)
  expect(Math.hypot(data.x - 330, data.y - 350)).toBeGreaterThan(100)
  await page.reload()
  await expect(actor).toHaveAttribute('data-phase', 'idle')
  expect(Number(await actor.getAttribute('data-x'))).toBeCloseTo(data.x, 0)
  expect(Number(await actor.getAttribute('data-y'))).toBeCloseTo(data.y, 0)
  await page.clock.runFor(4500)
  const moved = Number(await actor.getAttribute('data-x')) !== Number(data.x.toFixed(1)) || Number(await actor.getAttribute('data-y')) !== Number(data.y.toFixed(1))
  expect(moved).toBe(true)
})
test('native touch long press and cancellation work without page scrolling or sticky capture', async ({ page }) => {
  const session = await page.context().newCDPSession(page)
  await session.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 4 })
  const actor = page.getByTestId('room-bibi'), p = await point(actor)
  const scrollBefore = await page.evaluate(() => scrollY)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: p.x, y: p.y, id: 1 }] })
  await page.clock.runFor(1000)
  await expect(actor).toHaveAttribute('data-phase', 'petting')
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: p.x + 3, y: p.y + 1, id: 1 }] })
  await page.clock.runFor(1100)
  await expect(actor).toHaveAttribute('data-phase', 'bonding')
  expect((await saved(page, 'bibi')).stats.affection).toBe(23)
  expect(await page.evaluate(() => scrollY)).toBe(scrollBefore)
  await session.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await page.clock.runFor(1700)
  await expect(actor).toHaveAttribute('data-phase', 'idle')
  await session.detach()
})
test('all four characters react independently; focus loss and lost capture release them safely', async ({ page }) => {
  for (const id of ['momo', 'bibi', 'coco', 'dudu']) {
    const actor = page.getByTestId(`room-${id}`)
    await hold(page, actor); await release(page)
    expect((await saved(page, id)).stats.affection).toBe(21)
  }
  const actor = page.getByTestId('room-momo')
  await hold(page, actor)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.clock.runFor(100)
  await expect(actor).toHaveAttribute('data-phase', 'settling')
  await release(page)
  await page.clock.runFor(1700)
  await hold(page, actor)
  await actor.dispatchEvent('lostpointercapture', { pointerId: 1 })
  await page.clock.runFor(100)
  await expect(actor).toHaveAttribute('data-phase', 'settling')
  await release(page); await page.clock.runFor(1800)
  await expect(actor).toHaveAttribute('data-phase', 'idle')
  expect((await saved(page)).stats.affection).toBe(21)
})
test('legacy photos/stats survive, captured state resets on reload, and reward cooldown is retained', async ({ page }) => {
  const friends = createFriends(epoch.getTime())
  friends[0].photo = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = canvas.height = 32; const ctx = canvas.getContext('2d')!; ctx.fillStyle = '#e1b799'; ctx.fillRect(0, 0, 32, 32); return canvas.toDataURL('image/png') })
  friends[0].stats.affection = 76
  await page.addInitScript(data => { if (!sessionStorage.getItem('legacy-seeded')) { localStorage.setItem('pocket-friends-v1', JSON.stringify(data)); sessionStorage.setItem('legacy-seeded', '1') } }, { version: 1, savedAt: epoch.getTime() + 1001, friends, memories: [] })
  await page.reload()
  const actor = page.getByTestId('room-momo')
  await expect(actor.getByRole('img', { name: '모모의 등록 사진' })).toBeVisible()
  await expect(actor).toHaveAttribute('data-affinity', 'close')
  await hold(page, actor)
  await page.clock.runFor(2100)
  await expect(actor.locator('[data-expression]')).toHaveCount(0)
  await expect(actor.locator('.pet-heart')).toHaveCount(9)
  const data = await saved(page)
  expect(data.stats.affection).toBe(79)
  await page.reload(); await page.mouse.up()
  await expect(actor).toHaveAttribute('data-phase', 'idle')
  await hold(page, actor); await release(page)
  expect((await saved(page)).stats.affection).toBe(79)
  expect((await saved(page)).photo).toBe(friends[0].photo)
})
test('native touch taps and drags stay separate and multiple friends can be held at once', async ({ page }) => {
  const session = await page.context().newCDPSession(page)
  await session.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 4 })
  const coco = page.getByTestId('room-coco'), p = await point(coco)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...p, id: 1 }] })
  await page.clock.runFor(100)
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.clock.runFor(100)
  expect((await saved(page, 'coco')).stats.affection).toBe(21)
  const dudu = page.getByTestId('room-dudu'), q = await point(dudu)
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...q, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: q.x - 30, y: q.y + 20, id: 1 }] })
  await page.clock.runFor(300)
  await expect(dudu).toHaveAttribute('data-phase', 'dragging')
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.clock.runFor(100)
  await expect(dudu).toHaveAttribute('data-phase', 'landing')
  expect((await saved(page, 'dudu')).stats.affection).toBe(20)
  const a = await point(page.getByTestId('room-momo')), b = await point(page.getByTestId('room-bibi'))
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...a, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ ...a, id: 1 }, { ...b, id: 2 }] })
  await page.clock.runFor(2100)
  await expect(page.getByTestId('room-momo')).toHaveAttribute('data-phase', 'bonding')
  await expect(page.getByTestId('room-bibi')).toHaveAttribute('data-phase', 'bonding')
  expect((await saved(page, 'momo')).stats.affection).toBe(23)
  expect((await saved(page, 'bibi')).stats.affection).toBe(23)
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [{ ...b, id: 2 }] })
  await page.clock.runFor(100)
  await expect(page.getByTestId('room-bibi')).toHaveAttribute('data-phase', 'settling')
  await expect(page.getByTestId('room-momo')).toHaveAttribute('data-phase', 'bonding')
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.clock.runFor(1700)
  await expect(page.locator('.room-friend[data-phase=idle]')).toHaveCount(6)
  await session.detach()
})
